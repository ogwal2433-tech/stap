import { useState } from 'react';
import { Alert, Button, Form, Modal, Spinner } from 'react-bootstrap';
import { useApproveLetter, useSaveLetterEdits } from '../../hooks/useLetters';
import { LetterEditor } from './LetterEditor';
import LetterStatusBadge from './LetterStatusBadge';
import { DISCIPLINARY_LETTER_LABELS, HR_LETTER_LABELS, STRUCTURED_LETTER_TYPES } from '@stap/shared';
import type { GeneratedLetterResponse } from '@stap/shared';

interface Props {
  letter:  GeneratedLetterResponse;
  show:    boolean;
  onClose: () => void;
}

const LETTER_TYPE_LABELS: Record<string, string> = {
  ...DISCIPLINARY_LETTER_LABELS,
  ...HR_LETTER_LABELS,
};

export default function ApproveLetterModal({ letter, show, onClose }: Props) {
  const mutation     = useApproveLetter();
  const saveEdits     = useSaveLetterEdits();
  const [decision, setDecision]         = useState<'APPROVED' | 'REJECTED' | ''>('');
  const [approvalNotes, setApprovalNotes] = useState('');
  const [isEditing, setIsEditing]       = useState(false);
  const [editedBody, setEditedBody]     = useState(letter.body);

  const canEdit =
    letter.approvalStatus === 'PENDING' &&
    !(STRUCTURED_LETTER_TYPES as readonly string[]).includes(letter.letterType);

  const canSubmit =
    decision !== '' &&
    (decision !== 'REJECTED' || approvalNotes.trim().length > 0) &&
    !mutation.isPending;

  function handleClose() {
    setDecision('');
    setApprovalNotes('');
    setIsEditing(false);
    onClose();
  }

  function toggleEdit() {
    if (isEditing) setEditedBody(letter.body); // cancel — discard unsaved changes
    setIsEditing(!isEditing);
  }

  async function handleSaveEdits() {
    await saveEdits.mutateAsync({ id: letter.id, body: editedBody });
    setIsEditing(false);
  }

  async function handleSubmit() {
    if (!decision) return;
    await mutation.mutateAsync(
      { id: letter.id, data: { approvalStatus: decision, approvalNotes: approvalNotes || undefined } },
      { onSuccess: handleClose },
    );
  }

  return (
    <Modal show={show} onHide={handleClose} size="lg">
      <Modal.Header closeButton>
        <Modal.Title>Review Letter — Approve or Reject</Modal.Title>
      </Modal.Header>
      <Modal.Body>
        {/* Summary card */}
        <div style={{ background: '#F2F4F7', borderRadius: '0.5rem', padding: '12px 16px', marginBottom: 16 }}>
          <div className="fw-bold" style={{ color: '#1B3A6B' }}>{letter.title}</div>
          <div className="text-muted small mt-1">
            {LETTER_TYPE_LABELS[letter.letterType] ?? letter.letterType}
            {' · For: '}{letter.subjectName}
            {' · Generated by: '}{letter.generatedBy.name}
            {' · '}{new Date(letter.generatedAt).toLocaleDateString('en-GB')}
          </div>
          <div className="mt-1">
            <LetterStatusBadge status={letter.approvalStatus} />
          </div>
        </div>

        {/* Letter body preview / edit */}
        <div className="mb-3">
          <div className="d-flex align-items-center justify-content-between mb-1">
            <Form.Label className="fw-bold small mb-0">Letter Content</Form.Label>
            {canEdit && (
              <Button
                size="sm"
                variant={isEditing ? 'outline-secondary' : 'outline-primary'}
                style={{ fontSize: '0.75rem' }}
                onClick={toggleEdit}
              >
                {isEditing ? '✕ Cancel Edit' : '✏️ Edit Letter'}
              </Button>
            )}
          </div>
          <LetterEditor
            key={isEditing ? 'edit' : 'view'}
            content={editedBody}
            onChange={isEditing ? setEditedBody : undefined}
            readOnly={!isEditing}
            minHeight="240px"
          />
          {isEditing && editedBody !== letter.body && (
            <div className="mt-2">
              <Button
                variant="outline-primary"
                size="sm"
                onClick={handleSaveEdits}
                disabled={saveEdits.isPending}
              >
                {saveEdits.isPending ? 'Saving…' : '💾 Save Letter Edits'}
              </Button>
              <span className="text-muted small ms-2">Save your edits, then approve below.</span>
            </div>
          )}
        </div>

        {/* Decision buttons */}
        <div className="mb-3">
          <Form.Label className="fw-bold small">Decision <span className="text-danger">*</span></Form.Label>
          <div className="d-flex gap-2">
            {[
              { key: 'APPROVED' as const, label: 'Approve', sub: 'Mark as official',    color: '#1E8449', bg: '#d5f5e3' },
              { key: 'REJECTED' as const, label: 'Reject',  sub: 'Return for revision', color: '#842029', bg: '#f8d7da' },
            ].map(({ key, label, sub, color, bg }) => (
              <button
                key={key}
                type="button"
                onClick={() => setDecision(key)}
                style={{
                  flex: 1, padding: 10, borderRadius: '0.5rem', cursor: 'pointer', textAlign: 'center',
                  border:      `2px solid ${decision === key ? color : '#ced4da'}`,
                  background:  decision === key ? bg    : '#fff',
                  fontWeight:  decision === key ? 600   : 400,
                  color:       decision === key ? color : '#4A5568',
                }}
              >
                {label}
                <div style={{ fontSize: '0.75rem', fontWeight: 400, marginTop: 2 }}>{sub}</div>
              </button>
            ))}
          </div>
        </div>

        {/* Notes field */}
        <Form.Group>
          <Form.Label className="small fw-bold">
            Notes
            {decision === 'REJECTED'
              ? <span className="text-danger"> *</span>
              : <span className="text-muted fw-normal ms-1">(optional)</span>}
          </Form.Label>
          <Form.Control
            as="textarea"
            rows={3}
            placeholder={decision === 'REJECTED'
              ? 'Explain why this letter is rejected and what needs to change…'
              : 'Optional notes for the record…'}
            value={approvalNotes}
            onChange={e => setApprovalNotes(e.target.value)}
            isInvalid={decision === 'REJECTED' && approvalNotes.trim().length === 0}
          />
          {decision === 'REJECTED' && approvalNotes.trim().length === 0 && (
            <Form.Control.Feedback type="invalid">A reason is required when rejecting.</Form.Control.Feedback>
          )}
        </Form.Group>

        {mutation.isError && (
          <Alert variant="danger" className="mt-3 small py-2">
            {(mutation.error as any)?.response?.data?.error ?? 'Failed to submit decision.'}
          </Alert>
        )}
      </Modal.Body>
      <Modal.Footer>
        <Button variant="secondary" onClick={handleClose} disabled={mutation.isPending}>Cancel</Button>
        <Button
          variant={decision === 'APPROVED' ? 'success' : decision === 'REJECTED' ? 'danger' : 'primary'}
          disabled={!canSubmit}
          onClick={handleSubmit}
        >
          {mutation.isPending
            ? <Spinner size="sm" animation="border" />
            : decision === 'APPROVED' ? 'Confirm Approval'
            : decision === 'REJECTED' ? 'Confirm Rejection'
            : 'Make a Decision'}
        </Button>
      </Modal.Footer>
    </Modal>
  );
}
