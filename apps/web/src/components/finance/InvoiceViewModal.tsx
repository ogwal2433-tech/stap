import { Modal, Button, Table, Badge, Spinner } from 'react-bootstrap';
import { useState } from 'react';
import { useInvoice } from '../../hooks/useFinance';
import { invoicesApi } from '../../lib/finance.api';
import { useToast } from '../../context/ToastContext';
import type { InvoiceResponse } from '@stap/shared';

const NAVY = '#1B3A6B';

const fmtUGX = (n: number) => `UGX ${n.toLocaleString()}`;
const fmtDate = (iso: string) => new Date(iso).toLocaleDateString('en-GB');

const STATUS_BG: Record<string, string> = {
  PENDING: 'warning', OVERDUE: 'danger', PARTIALLY_PAID: 'info',
  PAID: 'success', VOID: 'dark',
};

/**
 * Read-only view of one invoice. The list rows carry no line items (the list
 * endpoint doesn't include them), so the full record is fetched by id.
 */
export default function InvoiceViewModal({
  invoice,
  onClose,
}: {
  invoice: InvoiceResponse;
  onClose: () => void;
}) {
  const { showToast } = useToast();
  const [pdfBusy, setPdfBusy] = useState(false);
  const { data: full, isLoading } = useInvoice(invoice.id);
  const inv = full ?? invoice;

  const openPdf = async () => {
    setPdfBusy(true);
    try {
      await invoicesApi.openInvoicePdf(invoice.id, invoice.invoiceNumber);
    } catch {
      showToast('Could not build the invoice PDF.', 'danger');
    } finally {
      setPdfBusy(false);
    }
  };

  return (
    <Modal show onHide={onClose} size="lg" centered>
      <Modal.Header closeButton>
        <Modal.Title className="h6 fw-bold" style={{ color: NAVY }}>
          Invoice {inv.invoiceNumber}{' '}
          <Badge bg={STATUS_BG[inv.status] ?? 'secondary'}>{inv.status}</Badge>
        </Modal.Title>
      </Modal.Header>
      <Modal.Body>
        {isLoading && !full ? (
          <div className="text-center py-4"><Spinner size="sm" className="me-2" />Loading invoice…</div>
        ) : (
          <>
            <Table size="sm" borderless className="small mb-3">
              <tbody>
                <tr><td className="text-muted" style={{ width: 150 }}>Client</td><td className="fw-medium">{inv.clientName}</td></tr>
                <tr><td className="text-muted">Billing period</td><td>{fmtDate(inv.periodStart)} – {fmtDate(inv.periodEnd)}</td></tr>
                <tr><td className="text-muted">Due date</td><td>{fmtDate(inv.dueDate)}</td></tr>
                <tr><td className="text-muted">Raised</td><td>{fmtDate(inv.createdAt)}{inv.autoGenerated ? ' (auto-generated)' : ''}</td></tr>
                {inv.emailSentAt && (
                  <tr><td className="text-muted">Emailed</td><td>{fmtDate(inv.emailSentAt)} to {inv.emailSentTo}</td></tr>
                )}
                {inv.status === 'VOID' && inv.voidReason && (
                  <tr><td className="text-muted">Void reason</td><td>{inv.voidReason}</td></tr>
                )}
              </tbody>
            </Table>

            {inv.lineItems.length > 0 && (
              <Table size="sm" bordered className="mb-2">
                <thead style={{ background: '#F2F4F7' }}>
                  <tr>
                    <th>Description</th>
                    <th style={{ width: 70 }} className="text-center">Qty</th>
                    <th style={{ width: 130 }} className="text-end">Rate / day</th>
                    <th style={{ width: 60 }} className="text-center">Days</th>
                    <th style={{ width: 140 }} className="text-end">Line total</th>
                  </tr>
                </thead>
                <tbody>
                  {inv.lineItems.map((li) => (
                    <tr key={li.id}>
                      <td className="small">{li.description}</td>
                      <td className="text-center small">{li.quantity}</td>
                      <td className="text-end small">{fmtUGX(li.ratePerDay)}</td>
                      <td className="text-center small">{li.days}</td>
                      <td className="text-end small fw-semibold">{fmtUGX(li.lineTotal)}</td>
                    </tr>
                  ))}
                </tbody>
                <tfoot>
                  <tr style={{ background: '#f8f9fa' }}>
                    <td colSpan={4} className="text-end fw-semibold small">Subtotal</td>
                    <td className="text-end fw-semibold small">{fmtUGX(inv.subtotal)}</td>
                  </tr>
                  {inv.taxAmount > 0 && (
                    <tr style={{ background: '#f8f9fa' }}>
                      <td colSpan={4} className="text-end fw-semibold small">Tax</td>
                      <td className="text-end fw-semibold small">{fmtUGX(inv.taxAmount)}</td>
                    </tr>
                  )}
                  <tr style={{ background: '#D0EDE9' }}>
                    <td colSpan={4} className="text-end fw-bold small">Total</td>
                    <td className="text-end fw-bold" style={{ color: '#0F7B6C' }}>{fmtUGX(inv.totalAmount)}</td>
                  </tr>
                  {inv.paidAmount > 0 && (
                    <>
                      <tr>
                        <td colSpan={4} className="text-end small text-success">Paid</td>
                        <td className="text-end small text-success">{fmtUGX(inv.paidAmount)}</td>
                      </tr>
                      <tr>
                        <td colSpan={4} className="text-end small fw-semibold">Outstanding</td>
                        <td className="text-end small fw-bold" style={{ color: '#C0392B' }}>{fmtUGX(inv.outstandingBalance)}</td>
                      </tr>
                    </>
                  )}
                </tfoot>
              </Table>
            )}

            {inv.payments.length > 0 && (
              <div className="small text-muted">
                {inv.payments.length} payment(s) recorded — {fmtUGX(inv.paidAmount)} received.
              </div>
            )}
          </>
        )}
      </Modal.Body>
      <Modal.Footer>
        <Button variant="outline-secondary" size="sm" disabled={pdfBusy} onClick={openPdf}>
          {pdfBusy ? <><Spinner size="sm" className="me-1" />Preparing…</> : '🖨️ Open PDF'}
        </Button>
        <Button variant="secondary" size="sm" onClick={onClose}>Close</Button>
      </Modal.Footer>
    </Modal>
  );
}
