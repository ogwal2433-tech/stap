import { describe, it, expect, vi, beforeEach } from 'vitest';
import ExcelJS from 'exceljs';

// ── Mocks ──────────────────────────────────────────────────────────────────────

vi.mock('../../db/prisma', () => ({
  default: {
    payrollRun: { findUnique: vi.fn() },
  },
}));

// Puppeteer must never launch in tests — stub the letterhead renderer and keep
// the HTML and options it was handed so the header block and render settings
// can be asserted.
const mockRenderToPdf = vi.fn().mockResolvedValue(Buffer.from('%PDF-1.4 stub'));
vi.mock('../../lib/pdfBase', () => ({
  renderToPdf: (html: string, opts: unknown) => mockRenderToPdf(html, opts),
}));

import prisma from '../../db/prisma';
import { payrollExportService } from '../../services/payrollExportService';

const mp = prisma as any;

const MOCK_EXPORT_RUN = {
  id: 'run-1', month: 4, year: 2026, status: 'APPROVED',
  zone: { id: 'zone-1', name: 'Kampala Team' },
  payslips: [
    {
      guard: { systemId: 'S360G0001', firstName: 'David', lastName: 'Ochieng' },
      daysWorked: 26, totalDays: 26, grossSalary: 480000,
      totalDeductions: 48000, netSalary: 432000, disbursementStatus: 'PENDING',
    },
    {
      guard: { systemId: 'S360G0002', firstName: 'Amina', lastName: 'Nakato' },
      daysWorked: 20, totalDays: 26, grossSalary: 400000,
      totalDeductions: 0, netSalary: 400000, disbursementStatus: 'SUCCESS',
    },
  ],
};

beforeEach(() => {
  vi.clearAllMocks();
  mp.payrollRun.findUnique.mockResolvedValue(MOCK_EXPORT_RUN);
});

/** Flattens every non-empty cell of the first worksheet into one string list. */
async function excelCells(buffer: Buffer): Promise<string[]> {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.load(buffer as unknown as ArrayBuffer);
  const values: string[] = [];
  wb.getWorksheet('Payroll')!.eachRow(row => {
    row.eachCell(cell => values.push(String(cell.value ?? '')));
  });
  return values;
}

describe('payroll Excel export', () => {
  it('stamps the header block with month, year, print date and generator', async () => {
    const { buffer, filename } = await payrollExportService.buildRunExcel('run-1', 'Aisha Director');
    const cells = await excelCells(buffer);

    expect(cells).toContain('Zone:');
    expect(cells).toContain('Kampala Team');
    expect(cells).toContain('Payroll Month:');
    expect(cells).toContain('April');
    expect(cells).toContain('Year:');
    expect(cells).toContain('2026');
    expect(cells).toContain('Print Date:');
    expect(cells).toContain('Generated By:');
    expect(cells).toContain('Aisha Director');
    // Zone name is sluged into the file name, spaces becoming underscores.
    expect(filename).toMatch(/_Payroll_Kampala_Team_Apr2026\.xlsx$/);
  });

  it('lists one row per payslip plus a totals row', async () => {
    const { buffer } = await payrollExportService.buildRunExcel('run-1', 'Aisha Director');
    const cells = await excelCells(buffer);

    expect(cells).toContain('David Ochieng');
    expect(cells).toContain('Amina Nakato');
    expect(cells).toContain('26/26');
    // Totals computed from the payslips, not echoed from the run header.
    expect(cells).toContain('880000'); // gross
    expect(cells).toContain('48000');  // deductions
    expect(cells).toContain('832000'); // net
  });

  it('throws 404 when the run does not exist', async () => {
    mp.payrollRun.findUnique.mockResolvedValue(null);
    await expect(payrollExportService.buildRunExcel('missing', 'Someone')).rejects.toThrow('Payroll run not found');
  });

  it('labels a legacy run without a zone as Company-wide', async () => {
    mp.payrollRun.findUnique.mockResolvedValue({ ...MOCK_EXPORT_RUN, zone: null });
    const { buffer, filename } = await payrollExportService.buildRunExcel('run-1', 'Aisha Director');
    const cells = await excelCells(buffer);
    expect(cells).toContain('Company-wide');
    expect(filename).toMatch(/_Payroll_Company_wide_Apr2026\.xlsx$/);
  });
});

describe('payroll PDF export', () => {
  it('renders the header block and payslip table into the letterhead', async () => {
    const { pdf, filename } = await payrollExportService.buildRunPdf('run-1', 'Aisha Director');

    expect(pdf.toString()).toContain('PDF');
    expect(filename).toMatch(/_Payroll_Kampala_Team_Apr2026\.pdf$/);

    const html = mockRenderToPdf.mock.calls[0][0];
    expect(html).toContain('PAYROLL SCHEDULE');
    expect(html).toContain('Zone');
    expect(html).toContain('Kampala Team');
    expect(html).toContain('Payroll Month');
    expect(html).toContain('April');
    expect(html).toContain('Print Date');
    expect(html).toContain('Generated By');
    expect(html).toContain('Aisha Director');
    expect(html).toContain('David Ochieng');
    expect(html).toContain('Amina Nakato');
  });

  it('renders with the centred logo-only header and without the watermark', async () => {
    await payrollExportService.buildRunPdf('run-1', 'Aisha Director');
    expect(mockRenderToPdf.mock.calls[0][1]).toEqual({
      logoFile:  'tiger_logo.jpeg',
      watermark: false,
      logoOnly:  true,
    });
  });

  it('escapes HTML in data-driven text', async () => {
    mp.payrollRun.findUnique.mockResolvedValue({
      ...MOCK_EXPORT_RUN,
      payslips: [{
        ...MOCK_EXPORT_RUN.payslips[0],
        guard: { systemId: 'SSLG0001', firstName: '<script>evil</script>', lastName: 'Ochieng' },
      }],
    });
    await payrollExportService.buildRunPdf('run-1', 'Aisha Director');
    const html = mockRenderToPdf.mock.calls.at(-1)![0];
    expect(html).not.toContain('<script>evil</script>');
    expect(html).toContain('&lt;script&gt;');
  });
});
