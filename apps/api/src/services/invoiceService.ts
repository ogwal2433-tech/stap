// round2 (imported above as an alias of @security360/shared roundMoney) is applied to
// every derived money figure: rates arriving here are already whole-or-2dp, but
// count × rate × days is exact in decimal and not in binary, and a subtotal sums
// several such products. Without the snap an invoice would store
// 4,999,999.9999999996 and every later balance comparison would inherit the dust.

function formatLineItem(li: any): InvoiceLineItemResponse {
  return {
    id:          li.id,
    guardId:     li.guardId ?? null,
    description: li.description,
    quantity:    li.guardsCount ?? 1,
    ratePerDay:  li.ratePerGuard,
    days:        li.days ?? 30,
    lineTotal:   li.amount,
  };
}

/** Client-facing heading: the stored one, else the billing month in words. */
function invoiceHeading(inv: any): string {
  if (inv.description) return inv.description;
  const d    = inv.periodStart instanceof Date ? inv.periodStart : new Date(inv.periodStart);
  const month = d.toLocaleString('en-GB', { month: 'long' });
  const year  = d.getFullYear();
  return year === new Date().getFullYear()
    ? `Security Services for the month of ${month}`
    : `Security Services for the month of ${month} ${year}`;
}

/** Resolves creator/issuer user ids to display names in one lookup. */
async function attachUserNames(rows: any[]): Promise<void> {
  const ids = [...new Set(rows.flatMap((r) => [r.createdBy, r.issuedBy].filter(Boolean)))] as string[];
  if (!ids.length) return;
  const users = await prisma.user.findMany({
    where: { id: { in: ids } }, select: { id: true, name: true },
  });
  const nameOf = new Map<string, string>(users.map((u) => [u.id, u.name] as [string, string]));
  for (const r of rows) {
    r.createdByName = r.createdBy ? nameOf.get(r.createdBy) ?? null : null;
    r.issuedByName  = r.issuedBy  ? nameOf.get(r.issuedBy)  ?? null : null;
  }
}

