// ── Helpers ────────────────────────────────────────────────────────────────────

function formatLineItem(li: any): InvoiceLineItemResponse {
  return {
    id:          li.id,
    guardId:     li.guardId ?? null,
    description: li.description,
    quantity:    li.guardsCount ?? 1,
    ratePerDay:  li.ratePerGuard,
    days:        li.days ?? 30,
    lineTotal:   li.amount,
  };
}

function formatInvoice(inv: any, payments: any[] = []): InvoiceResponse {
  return {
    id:             inv.id,
    invoiceNumber:  inv.invoiceNumber,
    clientId:       inv.clientId,
    clientName:     inv.client?.clientName ?? '',
    contractId:     inv.contractId,
    contractRef:    inv.contract ? `${inv.contract.id}` : null,
    periodStart:    inv.periodStart.toISOString(),
    periodEnd:      inv.periodEnd.toISOString(),
    guardsDeployed: inv.guardsDeployed,
    ratePerGuard:   inv.ratePerGuard,
    subtotal:       inv.subtotal,
    taxAmount:      inv.taxAmount,
    totalAmount:    inv.totalAmount,
    status:         inv.status,
    dueDate:        inv.dueDate.toISOString(),
    paidAt:         inv.paidAt?.toISOString() ?? null,
    pdfPath:        inv.pdfPath,
    yoPaymentRef:   inv.yoPaymentRef,
    emailSentAt:    inv.emailSentAt?.toISOString() ?? null,
    emailSentTo:    inv.emailSentTo ?? null,
    autoGenerated:  inv.autoGenerated ?? false,
    createdAt:      inv.createdAt.toISOString(),
    payments:       (payments ?? inv.payments ?? []).map(formatPayment),
    lineItems:      (inv.lineItems ?? []).map(formatLineItem),
  };
}

function formatPayment(p: any): PaymentResponse {
  return {
    id:              p.id,
    invoiceId:       p.invoiceId,
    amountPaid:      p.amountPaid,
    mode:            p.mode,
    referenceNumber: p.referenceNumber,
    yoTransactionId: p.yoTransactionId,
    reconciled:      p.reconciled,
    recordedBy:      p.recordedBy,
    createdAt:       p.createdAt.toISOString(),
  };
}

// ── InvoiceService ─────────────────────────────────────────────────────────────

class InvoiceService {
  private async generateInvoiceNumber(): Promise<string> {
    const year = new Date().getFullYear();
    const count = await prisma.invoice.count({
      where: { createdAt: { gte: new Date(`${year}-01-01`) } },
    });
    const seq = String(count + 1).padStart(4, '0');
    return `STAP/INV/${year}/${seq}`;
  }

  /**
   * The contract's guard rate lines are the only invoice source. ratePerGuard
   * on ContractGuardRate is a MONTHLY figure — convert to a daily rate here so
   * lineTotal = count * ratePerGuard * billingDays gives the correct amount
   * for the actual billing period instead of inflating it ~30x.
   */
  async getInvoicePreview(contractId: string, billingDays: number = 30): Promise<InvoicePreviewResponse> {
    const contract = await prisma.contract.findUnique({
      where:   { id: contractId },
      include: {
        client:     { select: { clientName: true } },
        guardRates: { orderBy: { createdAt: 'asc' } },
      },
    });
    if (!contract) throw new NotFoundError('Contract not found');

    if (!contract.guardRates.length) {
      throw new AppError(
        `This contract has no guard rate lines configured. ` +
        `Please edit the contract and add guard rate lines before generating an invoice.`,
        400,
      );
    }

    const lineItems = contract.guardRates.map((r) => {
      const ratePerDay = Math.round(r.ratePerGuard / 30);
      return {
        guardType:    r.guardType,
        count:        r.guardsCount,
        ratePerGuard: ratePerDay,
        billingDays,
        lineTotal:    r.guardsCount * ratePerDay * billingDays,
      };
    });

    const totalAmount    = lineItems.reduce((sum, li) => sum + li.lineTotal, 0);
    const guardsRequired = lineItems.reduce((sum, li) => sum + li.count, 0);

    return {
      contractId,
      clientName: contract.client.clientName,
      period:     `${billingDays} days`,
      lineItems,
      totalAmount,
      guardsRequired,
    };
  }

  async generateInvoice(data: GenerateInvoiceInput, generatedBy: string): Promise<InvoiceResponse> {
    const periodEnd = new Date(data.billingPeriodEnd);
    return this.generateInvoiceFromContract({
      contractId:  data.contractId,
      periodStart: new Date(data.billingPeriodStart),
      periodEnd,
      dueDate:     periodEnd,
      billingDays: data.billingDays,
      lineItemOverrides: data.lineItemOverrides,
      generatedBy,
    });
  }

  /** Shared by the manual "Generate Invoice" flow and the billing-day cron — the
   * contract's guard rate lines (via getInvoicePreview) are the only source of
   * line items either way; lineItemOverrides carries the user-edited preview rows. */
  private async generateInvoiceFromContract(params: {
    contractId:  string;
    periodStart: Date;
    periodEnd:   Date;
    dueDate:     Date;
    billingDays: number;
    lineItemOverrides?: GenerateInvoiceInput['lineItemOverrides'];
    generatedBy: string;
  }): Promise<InvoiceResponse> {
    const contract = await prisma.contract.findUnique({
      where:  { id: params.contractId },
      select: { clientId: true },
    });
    if (!contract) throw new NotFoundError('Contract not found');

    const rawItems = params.lineItemOverrides?.length
      ? params.lineItemOverrides
      : (await this.getInvoicePreview(params.contractId, params.billingDays)).lineItems;

    const lineItems = rawItems.map((li) => ({
      guardId:      null,
      description:  li.guardType,
      guardsCount:  li.count,
      ratePerGuard: li.ratePerGuard,
      days:         li.billingDays,
      amount:       li.count * li.ratePerGuard * li.billingDays,
    }));

    const totalAmount  = lineItems.reduce((sum, li) => sum + li.amount, 0);
    const invoiceNumber = await this.generateInvoiceNumber();

    const invoice = await prisma.invoice.create({
      data: {
        clientId:       contract.clientId,
        contractId:     params.contractId,
        invoiceNumber,
        periodStart:    params.periodStart,
        periodEnd:      params.periodEnd,
        guardsDeployed: lineItems.reduce((sum, li) => sum + li.guardsCount, 0),
        ratePerGuard:   0,
        subtotal:       totalAmount,
        taxAmount:      0,
        totalAmount,
        dueDate:        params.dueDate,
        createdBy:      params.generatedBy,
        lineItems: { create: lineItems },
      },
      include: { client: true, contract: true, payments: true, lineItems: true },
    });

    await QueueService.logAudit({
      userId:   params.generatedBy,
      action:   'INVOICE_GENERATED',
      entity:   'invoice',
      entityId: invoice.id,
      newValue: { contractId: params.contractId, lineItemCount: lineItems.length, totalAmount },
    });

    return formatInvoice(invoice);
  }

  async create(data: CreateInvoiceInput, createdBy: string): Promise<InvoiceResponse> {
    const client = await prisma.client.findUnique({ where: { id: data.clientId } });
    if (!client) throw new NotFoundError('Client not found');

    const subtotal     = data.guardsDeployed * data.ratePerGuard;
    const totalAmount  = subtotal + (data.taxAmount ?? 0);
    const invoiceNumber = await this.generateInvoiceNumber();

    const invoice = await prisma.invoice.create({
      data: {
        clientId:       data.clientId,
        contractId:     data.contractId ?? null,
        invoiceNumber,
        periodStart:    new Date(data.periodStart),
        periodEnd:      new Date(data.periodEnd),
        guardsDeployed: data.guardsDeployed,
        ratePerGuard:   data.ratePerGuard,
        subtotal,
        taxAmount:      data.taxAmount ?? 0,
        totalAmount,
        dueDate:        new Date(data.dueDate),
        createdBy,
      },
      include: { client: true, contract: true, payments: true },
    });

    await QueueService.generateInvoice({
      clientId:   invoice.clientId,
      contractId: invoice.contractId ?? '',
      periodStart: invoice.periodStart.toISOString(),
      periodEnd:   invoice.periodEnd.toISOString(),
    });

    if (client.email) {
      await QueueService.sendEmail({
        to:       client.email,
        subject:  `Invoice ${invoiceNumber} from STAP Security Ltd`,
        template: 'invoice',
        data: {
          invoiceNumber,
          totalAmount,
          dueDate:    invoice.dueDate.toISOString(),
          clientName: client.clientName,
        },
      });
    }

    await QueueService.logAudit({
      userId:   createdBy,
      action:   'INVOICE_CREATED',
      entity:   'invoice',
      entityId: invoice.id,
      newValue: { invoiceNumber, totalAmount },
    });

    return formatInvoice(invoice);
  }

  async generateAutoInvoices(): Promise<void> {
    const today     = new Date();
    const dayOfMonth = today.getDate();
    const daysInMonth = new Date(today.getFullYear(), today.getMonth() + 1, 0).getDate();
    const isLastDay  = dayOfMonth === daysInMonth;

    const contracts = await prisma.contract.findMany({
      where: {
        status: 'ACTIVE',
        OR: [
          { billingDay: dayOfMonth },
          // Last day of month covers contracts with billingDay > days in month
          ...(isLastDay ? [{ billingDay: { gt: daysInMonth } }] : []),
        ],
      },
      include: { client: true },
    });

    const periodStart = new Date(today.getFullYear(), today.getMonth(), 1);
    const periodEnd   = new Date(today.getFullYear(), today.getMonth() + 1, 0, 23, 59, 59);

    let generated = 0;
    for (const contract of contracts) {
      // Prevent duplicates
      const existing = await prisma.invoice.findFirst({
        where: {
          contractId:  contract.id,
          periodStart: { gte: periodStart },
          periodEnd:   { lte: periodEnd },
        },
      });
      if (existing) continue;

      const billingTerms = contract.client.billingTerms ?? 30;
      const dueDate = new Date(today);
      dueDate.setDate(dueDate.getDate() + billingTerms);

      try {
        await this.generateInvoiceFromContract({
          contractId: contract.id,
          periodStart,
          periodEnd,
          dueDate,
          billingDays: daysInMonth,
          generatedBy: 'system',
        });
        generated++;
      } catch (err) {
        // A contract with no guard rate lines (or other per-contract issue) shouldn't
        // block auto-invoicing for the rest of the batch.
        console.error(`[AutoInvoice] Failed for contract ${contract.id}:`, (err as Error).message);
      }
    }

    console.log(`Auto-generated ${generated} invoices for ${today.toDateString()}`);
  }

  async list(query: {
    clientId?: string;
    status?: string;
    page: number;
    limit: number;
    from?: string;
    to?: string;
  }): Promise<PaginatedResponse<InvoiceResponse>> {
    const { page, limit, clientId, status, from, to } = query;
    const skip = (page - 1) * limit;

    const where: any = {};
    if (clientId) where.clientId = clientId;
    if (status)   where.status   = status;
    if (from || to) {
      where.createdAt = {};
      if (from) where.createdAt.gte = new Date(from);
      if (to)   where.createdAt.lte = new Date(to);
    }

    const [invoices, total] = await Promise.all([
      prisma.invoice.findMany({
        where,
        include: { client: true, contract: true, payments: true },
        orderBy: { createdAt: 'desc' },
        skip,
        take: limit,
      }),
      prisma.invoice.count({ where }),
    ]);

    // Auto-mark overdue
    const now = new Date();
    for (const inv of invoices) {
      if (inv.status === 'PENDING' && inv.dueDate < now) {
        await prisma.invoice.update({ where: { id: inv.id }, data: { status: 'OVERDUE' } });
        inv.status = 'OVERDUE';
      }
    }

    const totalPages = Math.ceil(total / limit);
    return {
      data: invoices.map((i) => formatInvoice(i)),
      pagination: { page, limit, total, totalPages, hasNext: page < totalPages, hasPrev: page > 1 },
    };
  }

  async getById(id: string): Promise<InvoiceResponse> {
    const invoice = await prisma.invoice.findUnique({
      where:   { id },
      include: { client: true, contract: true, payments: true, lineItems: true },
    });
    if (!invoice) throw new NotFoundError('Invoice not found');
    return formatInvoice(invoice);
  }

  async recordManualPayment(data: RecordPaymentInput, recordedBy: string): Promise<PaymentResponse> {
    const invoice = await prisma.invoice.findUnique({
      where: { id: data.invoiceId },
      select: { totalAmount: true },
    });
    if (!invoice) throw new NotFoundError('Invoice not found');

    const payment = await prisma.payment.create({
      data: {
        invoiceId:       data.invoiceId,
        amountPaid:      data.amountPaid,
        mode:            data.mode,
        referenceNumber: data.referenceNumber ?? null,
        recordedBy,
      },
    });

    // Sum all payments including the one just created
    const agg = await prisma.payment.aggregate({
      where: { invoiceId: data.invoiceId },
      _sum:  { amountPaid: true },
    });
    const sumPaid = agg._sum.amountPaid ?? 0;

    if (sumPaid >= invoice.totalAmount) {
      await prisma.invoice.update({
        where: { id: data.invoiceId },
        data:  { status: 'PAID', paidAt: new Date() },
      });
    }

    await QueueService.logAudit({
      userId:   recordedBy,
      action:   'PAYMENT_RECORDED',
      entity:   'payment',
      entityId: payment.id,
      newValue: { invoiceId: data.invoiceId, amountPaid: data.amountPaid },
    });

    return formatPayment(payment);
  }

  async getARAgingReport(): Promise<ARAgingReport> {
    const now = new Date();

    // Auto-mark overdue
    await prisma.invoice.updateMany({
      where:  { status: 'PENDING', dueDate: { lt: now } },
      data:   { status: 'OVERDUE' },
    });

    const invoices = await prisma.invoice.findMany({
      where:   { status: { in: ['PENDING', 'OVERDUE'] } },
      include: { client: true, contract: true, payments: true },
      orderBy: { dueDate: 'asc' },
    });

    const buckets = { current: 0, days31_60: 0, days61_90: 0, over90: 0, total: 0 };

    for (const inv of invoices) {
      const daysOverdue = Math.floor((now.getTime() - inv.dueDate.getTime()) / 86_400_000);
      buckets.total += inv.totalAmount;
      if (daysOverdue <= 0)       buckets.current   += inv.totalAmount;
      else if (daysOverdue <= 30) buckets.current   += inv.totalAmount;
      else if (daysOverdue <= 60) buckets.days31_60 += inv.totalAmount;
      else if (daysOverdue <= 90) buckets.days61_90 += inv.totalAmount;
      else                         buckets.over90    += inv.totalAmount;
    }

    return { invoices: invoices.map((i) => formatInvoice(i)), buckets };
  }

  async initiateYoPayment(invoiceId: string): Promise<{ paymentRef: string; status: string }> {
    const invoice = await prisma.invoice.findUnique({
      where: { id: invoiceId },
      include: { client: true },
    });
    if (!invoice) throw new NotFoundError('Invoice not found');
    if (!['PENDING', 'OVERDUE'].includes(invoice.status)) {
      throw new AppError('Invoice is not payable', 400);
    }

    const prefix = process.env.YO_INTERNAL_REFERENCE_PREFIX ?? 'STAP';
    const resp = await yoPayments.requestPayment({
      amount:            invoice.totalAmount,
      msisdn:            invoice.client.contactPhone,
      narrative:         `Invoice ${invoice.invoiceNumber} — STAP Security Ltd`,
      internalReference: `${prefix}-INV-${invoice.id}`,
    });

    await prisma.invoice.update({
      where: { id: invoiceId },
      data:  { yoPaymentRef: resp.transactionRef },
    });

    await QueueService.logAudit({
      action:   'YO_PAYMENT_INITIATED',
      entity:   'invoice',
      entityId: invoiceId,
      newValue: { paymentRef: resp.transactionRef },
    });

    return { paymentRef: resp.transactionRef, status: resp.status };
  }

  async sendInvoiceEmail(invoiceId: string): Promise<void> {
    const invoice = await prisma.invoice.findUnique({
      where:   { id: invoiceId },
      include: { client: true, lineItems: true },
    });
    if (!invoice) throw new NotFoundError('Invoice not found');

    const recipientEmail = invoice.client.email;
    if (!recipientEmail) {
      console.warn(`[Invoice] No email for client ${invoice.client.clientName} — skipping email for invoice ${invoice.id}`);
      return;
    }

    const lineItems = invoice.lineItems.length
      ? invoice.lineItems.map((li) => ({
          description: li.description,
          qty:         li.guardsCount,
          unitPrice:   li.ratePerGuard,
          total:       li.amount,
        }))
      : [
          {
            description: `Security Services — ${invoice.guardsDeployed} guard${invoice.guardsDeployed !== 1 ? 's' : ''} × UGX ${invoice.ratePerGuard.toLocaleString()}/month`,
            qty:         invoice.guardsDeployed,
            unitPrice:   invoice.ratePerGuard,
            total:       invoice.subtotal,
          },
        ];

    const html = buildInvoiceEmail({
      clientName:    invoice.client.clientName,
      invoiceNumber: invoice.invoiceNumber,
      issueDate:     new Date(invoice.createdAt).toLocaleDateString('en-GB'),
      dueDate:       new Date(invoice.dueDate).toLocaleDateString('en-GB'),
      lineItems,
      subtotal:      invoice.subtotal,
      tax:           invoice.taxAmount,
      totalAmount:   invoice.totalAmount,
      currency:      'UGX',
    });

    await sendEmail({
      to:      recipientEmail,
      subject: `Invoice ${invoice.invoiceNumber} — STAP Security Ltd — Due ${new Date(invoice.dueDate).toLocaleDateString('en-GB')}`,
      html,
    });

    await prisma.invoice.update({
      where: { id: invoiceId },
      data:  { emailSentAt: new Date(), emailSentTo: recipientEmail },
    });

    console.log(`✅ Invoice email sent to ${recipientEmail} for ${invoice.client.clientName}`);
  }

  async handleYoWebhook(payload: any): Promise<void> {
    // Yo! Payments webhook format varies by merchant configuration.
    // Adjust payload parsing when merchant account is confirmed.
    const ref = payload?.InternalReference as string | undefined;
    if (!ref) return;

    const invoiceId = ref.replace(/^[A-Z]+-INV-/, '');
    const invoice   = await prisma.invoice.findUnique({ where: { id: invoiceId } });
    if (!invoice) return;

    if (payload?.TransactionStatus === 'COMPLETED') {
      await this.recordManualPayment(
        {
          invoiceId,
          amountPaid:      Number(payload.Amount ?? invoice.totalAmount),
          mode:            'MOBILE_MONEY',
          referenceNumber: payload.TransactionReference,
        },
        'system',
      );
    }
  }
}

export const invoiceService = new InvoiceService();
