  async getARAgingReport(
    query: { clientId?: string; from?: string; to?: string } = {},
  ): Promise<ARAgingReport> {
    const now = new Date();

    // Auto-mark overdue: issued invoices age on their own, and so does a
    // manually raised PENDING one (no runBatchId — it never gets an issue
    // step). A run batch still awaiting the MD's approval never reached the
    // client and must not age while the report is being read.
    await prisma.invoice.updateMany({
      where:  {
        dueDate: { lt: now },
        OR: [
          { status: 'ISSUED' },
          { status: 'PENDING', runBatchId: null },
        ],
      },
      data:   { status: 'OVERDUE' },
    });

    const { clientId, from, to } = query;
    const where: any = { status: { in: [...OUTSTANDING_STATUSES] } };
    if (clientId) where.clientId = clientId;
    // The two dates match either the day the invoice was raised or a billing
    // period straddling the window (a September invoice raised in October is
    // still a September invoice) — the same widening the invoice list offers,
    // so both screens answer a window search the same way. The buckets
    // themselves still age by due date.
    const raised = dateRangeFilter(from, to, true);
    if (raised) {
      where.OR = [
        { createdAt: raised },
        {
          periodStart: raised.lte ? { lte: raised.lte } : {},
          periodEnd:   raised.gte ? { gte: raised.gte } : {},
        },
      ];
    }

    const invoices = await prisma.invoice.findMany({
      where,
      include: { client: true, contract: true, payments: true },
      orderBy: { dueDate: 'asc' },
    });

    const buckets = { current: 0, days31_60: 0, days61_90: 0, over90: 0, total: 0 };

    for (const inv of invoices) {
      const daysOverdue = Math.floor((now.getTime() - inv.dueDate.getTime()) / 86_400_000);
      // What is still owed, not what was billed — ageing the full total kept a
      // part-paid invoice in the report at its original size.
      const owed = inv.outstandingBalance;
      buckets.total += owed;
      if (daysOverdue <= 0)       buckets.current   += owed;
      else if (daysOverdue <= 30) buckets.current   += owed;
      else if (daysOverdue <= 60) buckets.days31_60 += owed;
      else if (daysOverdue <= 90) buckets.days61_90 += owed;
      else                         buckets.over90    += owed;
    }

    // Adding a column of two-decimal floats leaves binary dust behind, and these
    // buckets go straight into the finance page's tiles.
    for (const key of Object.keys(buckets) as (keyof typeof buckets)[]) {
      buckets[key] = round2(buckets[key]);
    }

    return { invoices: invoices.map((i) => formatInvoice(i)), buckets };
  }

  async initiateYoPayment(invoiceId: string): Promise<{ paymentRef: string; status: string }> {
    const invoice = await prisma.invoice.findUnique({
      where: { id: invoiceId },
      include: { client: true },
    });
    if (!invoice) throw new NotFoundError('Invoice not found');
    if (!(OUTSTANDING_STATUSES as readonly string[]).includes(invoice.status)) {
      throw new AppError('Invoice is not payable', 400);
    }

    // The client's contact phone is the number charged. A client saved without
    // one — every Excel import — or before phones were normalised would reach Yo
    // as a blank or dashed MSISDN and fail with an error naming neither.
    const msisdn = normaliseClientPhone(invoice.client.contactPhone ?? '');
    if (!CLIENT_PHONE_PATTERN.test(msisdn)) {
      throw new AppError(
        `${invoice.client.clientName} has no valid phone number to charge. ` +
        'Add one to their primary contact, then try again.',
        400,
      );
    }

    const prefix = process.env.YO_INTERNAL_REFERENCE_PREFIX ?? 'S360';
    const resp = await yoPayments.requestPayment({
      amount:            invoice.totalAmount,
      msisdn,
      narrative:         `Invoice ${invoice.invoiceNumber} — ${(await companyProfile()).name}`,
      internalReference: `${prefix}-INV-${invoice.id}`,
    });

    await prisma.invoice.update({
      where: { id: invoiceId },
      data:  { yoPaymentRef: resp.transactionRef },
    });

    await QueueService.logAudit({
      action:   'YO_PAYMENT_INITIATED',
      entity:   'invoice',
      entityId: invoiceId,
      newValue: { paymentRef: resp.transactionRef },
    });

    return { paymentRef: resp.transactionRef, status: resp.status };
  }

