import ExcelJS from 'exceljs';
import { COMPANY_NAME, FILE_PREFIX } from '../config/branding';
import prisma from '../db/prisma';
import { NotFoundError } from '../errors/AppError';
import { renderToPdf } from '../lib/pdfBase';
import {
  buildPayrollRunPdfHtml,
  type PayrollExportRow,
  type PayrollRunPdfData,
} from '../lib/templates/payrollRunPdf';

// ── Constants ──────────────────────────────────────────────────────────────────

const MONTH_NAMES = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December',
];

const NAVY  = 'FF1B3A6B';
const AMBER = 'FFF2AA20';
const WHITE = 'FFFFFFFF';

// ── Helpers ────────────────────────────────────────────────────────────────────

function monthName(month: number): string {
  return MONTH_NAMES[month - 1] ?? String(month);
}

function fmtPrintDate(d: Date): string {
  return d.toLocaleString('en-GB', {
    day:   'numeric',
    month: 'long',
    year:  'numeric',
    hour:  '2-digit',
    minute:'2-digit',
  });
}

// Zone names go into file names, so spaces and punctuation become underscores.
function slugify(s: string): string {
  return s.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

interface ExportPayload {
  run: any;
  rows: PayrollExportRow[];
  pdfData: PayrollRunPdfData;
  filenameBase: string;
}

// ── Service ────────────────────────────────────────────────────────────────────

/**
 * Printable exports of a calculated payroll run (Excel and PDF).
 *
 * Both formats carry the same header block — Zone, Payroll Month, Year,
 * Print Date and Generated By — so a printed schedule can always be traced
 * back to the run, the zone, the period and the person who exported it.
 */
class PayrollExportService {
  private async loadPayload(runId: string, generatedBy: string, printDate: Date): Promise<ExportPayload> {
    const run = await prisma.payrollRun.findUnique({
      where:   { id: runId },
      include: {
        zone:         true,
        payslips:     { include: { guard: true }, orderBy: { guard: { firstName: 'asc' } } },
      },
    });
    if (!run) throw new NotFoundError('Payroll run not found');

    const rows: PayrollExportRow[] = run.payslips.map((p: any, i: number) => ({
      index:         i + 1,
      systemId:      p.guard?.systemId ?? '',
      guardName:     p.guard ? `${p.guard.firstName} ${p.guard.lastName}` : '—',
      daysWorked:    p.daysWorked,
      totalDays:     p.totalDays,
      gross:         p.grossSalary,
      deductions:    p.totalDeductions,
      net:           p.netSalary,
      paymentStatus: p.disbursementStatus,
    }));

    const totalGross      = rows.reduce((s, r) => s + r.gross, 0);
    const totalDeductions = rows.reduce((s, r) => s + r.deductions, 0);
    const totalNet        = rows.reduce((s, r) => s + r.net, 0);

    const pdfData: PayrollRunPdfData = {
      monthName:       monthName(run.month),
      year:            run.year,
      // Legacy runs predate zone payroll and carry no zone.
      zoneName:        run.zone?.name ?? 'Company-wide',
      printDate:       fmtPrintDate(printDate),
      generatedBy,
      status:          run.status,
      guardCount:      rows.length,
      totalGross,
      totalDeductions,
      totalNet,
      rows,
    };

    const filenameBase = `${FILE_PREFIX}_Payroll_${slugify(pdfData.zoneName)}_${MONTH_NAMES[run.month - 1]?.slice(0, 3) ?? run.month}${run.year}`;

    return { run, rows, pdfData, filenameBase };
  }

  // ── Excel ────────────────────────────────────────────────────────────────────

  async buildRunExcel(runId: string, generatedBy: string): Promise<{ buffer: Buffer; filename: string }> {
    const printDate = new Date();
    const { rows, pdfData, filenameBase } = await this.loadPayload(runId, generatedBy, printDate);

    const NUM_COLS = 8;
    const wb = new ExcelJS.Workbook();
    wb.creator = COMPANY_NAME;
    const ws = wb.addWorksheet('Payroll');

    const bannerRow = (text: string, fillArgb: string, fontArgb: string, size: number) => {
      const row = ws.addRow([text]);
      ws.mergeCells(row.number, 1, row.number, NUM_COLS);
      row.height = size + 8;
      const cell = row.getCell(1);
      cell.fill   = { type: 'pattern', pattern: 'solid', fgColor: { argb: fillArgb } };
      cell.font   = { bold: true, size, color: { argb: fontArgb } };
      cell.alignment = { horizontal: 'center', vertical: 'middle' };
      return row;
    };

    // ── Header block: what period, when printed, by whom ──────────────────────
    bannerRow(COMPANY_NAME.toUpperCase(), NAVY, WHITE, 14);
    bannerRow('PAYROLL SCHEDULE', AMBER, NAVY, 12);
    ws.addRow([]);

    const meta = (label: string, value: string | number) => {
      const row = ws.addRow([label, value]);
      ws.mergeCells(row.number, 2, row.number, NUM_COLS);
      row.height = 16;
      row.getCell(1).font = { bold: true, color: { argb: 'FF4A5568' } };
      row.getCell(2).alignment = { horizontal: 'left' };
    };
    meta('Zone:',          pdfData.zoneName);
    meta('Payroll Month:', pdfData.monthName);
    meta('Year:',         pdfData.year);
    meta('Print Date:',   pdfData.printDate);
    meta('Generated By:', generatedBy);
    meta('Run Status:',   pdfData.status);
    ws.addRow([]);

    // ── Payslip table ──────────────────────────────────────────────────────────
    const header = ws.addRow(['#', 'System ID', 'Guard Name', 'Days Worked', 'Gross (UGX)', 'Deductions (UGX)', 'Net (UGX)', 'Payment Status']);
    header.height = 20;
    header.eachCell(cell => {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY } };
      cell.font = { bold: true, color: { argb: WHITE } };
      cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
    });

    rows.forEach((r, i) => {
      const row = ws.addRow([
        r.index, r.systemId, r.guardName, `${r.daysWorked}/${r.totalDays}`,
        r.gross, r.deductions, r.net, r.paymentStatus,
      ]);
      if (i % 2 === 0) {
        row.eachCell(cell => {
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF5F5F5' } };
        });
      }
      [5, 6, 7].forEach(c => {
        const cell = row.getCell(c);
        cell.numFmt   = '#,##0';
        cell.alignment = { horizontal: 'right' };
      });
      row.getCell(4).alignment = { horizontal: 'center' };
      row.getCell(8).alignment = { horizontal: 'center' };
    });

    const totals = ws.addRow(['', '', `${rows.length} guard(s)`, '', pdfData.totalGross, pdfData.totalDeductions, pdfData.totalNet, '']);
    totals.height = 20;
    totals.eachCell(cell => {
      cell.font = { bold: true, color: { argb: WHITE } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY } };
    });
    [5, 6, 7].forEach(c => {
      totals.getCell(c).numFmt   = '#,##0';
      totals.getCell(c).alignment = { horizontal: 'right' };
    });

    [5, 12, 28, 13, 15, 18, 15, 16].forEach((w, i) => { ws.getColumn(i + 1).width = w; });
    ws.views = [{ state: 'frozen', ySplit: header.number }];

    const arrayBuffer = await wb.xlsx.writeBuffer();
    return { buffer: Buffer.from(arrayBuffer), filename: `${filenameBase}.xlsx` };
  }

  // ── PDF ──────────────────────────────────────────────────────────────────────

  async buildRunPdf(runId: string, generatedBy: string): Promise<{ pdf: Buffer; filename: string }> {
    const printDate = new Date();
    const { pdfData, filenameBase } = await this.loadPayload(runId, generatedBy, printDate);

    // The payroll schedule header is the tiger logo alone, centred — no
    // company name band and no watermark; it is a working document meant to
    // be read and signed.
    const pdf = await renderToPdf(buildPayrollRunPdfHtml(pdfData), {
      logoFile:  'tiger_logo.jpeg',
      watermark: false,
      logoOnly:  true,
    });
    return { pdf, filename: `${filenameBase}.pdf` };
  }
}

export const payrollExportService = new PayrollExportService();
